    "#!/usr/bin/env python3\n",
    "\"\"\"\n",
    "Parse the standard form header AND the Purpose statement from every SOP.\n",
    "\n",
    "Adds to each record: reference_number, subject, effective_date (date only),\n",
    "replaces, and purpose (the sentence(s) after 'I. PURPOSE', with the common\n",
    "\"Establish guidelines for...\" opener already stripped).\n",
    "\n",
    "Run this AFTER fetch_sops.py. Reads sops/nodes.json + sops/text/*.txt,\n",
    "writes sops/nodes_enriched.json.\n",
    "\"\"\"\n",
    "\n",
    "import re\n",
    "import json\n",
    "import pathlib\n",
    "\n",
    "SOP_DIR = pathlib.Path(\"sops\")\n",
    "\n",
    "LABELS = [\"Reference Number\", \"Subject\", \"Special Instructions\", \"Effective Date\"]\n",
    "\n",
    "# ---- header ---------------------------------------------------------------\n",
    "\n",
    "def parse_header(text):\n",
    "    clean = re.sub(r\"[ \\t]+\", \" \", text[:1000])\n",
    "    clean = re.sub(r\" *\\n *\", \"\\n\", clean)\n",
    "\n",
    "    def field(label, stop_labels):\n",
    "        stops = \"|\".join(re.escape(s) for s in stop_labels)\n",
    "        pat = rf\"{re.escape(label)}\\s*\\n?\\s*(.+?)(?:\\n(?:{stops})|\\Z)\"\n",
    "        m = re.search(pat, clean, re.DOTALL)\n",
    "        if not m:\n",
    "            return None\n",
    "        return re.sub(r\"\\s+\", \" \", m.group(1)).strip() or None\n",
    "\n",
    "    others = lambda cur: [l for l in LABELS if l != cur]\n",
    "    ref = field(\"Reference Number\", others(\"Reference Number\"))\n",
    "    subj = field(\"Subject\", others(\"Subject\"))\n",
    "    special = field(\"Special Instructions\", others(\"Special Instructions\"))\n",
    "    eff = field(\"Effective Date\", others(\"Effective Date\"))\n",
    "\n",
    "    # cap effective date to just the date (it's the last label, so it\n",
    "    # otherwise swallows the whole body)\n",
    "    if eff:\n",
    "        m = re.match(r\"([A-Z][a-z]+ \\d{1,2},? \\d{4})\", eff)\n",
    "        eff = m.group(1) if m else eff.split(\"\\n\")[0][:40]\n",
    "\n",
    "    replaces = special if (special and \"replace\" in special.lower()) else None\n",
    "\n",
    "    return {\n",
    "        \"reference_number\": ref,\n",
    "        \"subject\": subj,\n",
    "        \"replaces\": replaces,\n",
    "        \"effective_date\": eff,\n",
    "    }\n",
    "\n",
    "# ---- purpose ----------------------------------------------------------------\n",
    "\n",
    "def extract_purpose(text):\n",
    "    \"\"\"The sentence(s) after 'I. PURPOSE', up to the next section (II./III.),\n",
    "    with the boilerplate 'Establish guidelines for...' opener stripped.\"\"\"\n",
    "    clean = re.sub(r\"[ \\t]+\", \" \", text)\n",
    "    m = re.search(\n",
    "        r\"I\\.\\s*PURPOSE\\s*(.+?)(?:\\n\\s*(?:II|III)\\.\\s|\\Z)\",\n",
    "        clean, re.DOTALL | re.IGNORECASE)\n",
    "    if not m:\n",
    "        return None\n",
    "    purpose = re.sub(r\"\\s+\", \" \", m.group(1)).strip()\n",
    "    # strip the common opener so downstream signals see only the\n",
    "    # distinctive part\n",
    "    purpose = re.sub(r\"^Establish(es)?\\s+(guidelines?|procedures?)\\s+(for|to)\\s+\",\n",
    "                     \"\", purpose, flags=re.IGNORECASE).strip()\n",
    "    return purpose[:600] or None\n",
    "\n",
    "# ---- quality check ----------------------------------------------------------\n",
    "\n",
    "def looks_clean(subject):\n",
    "    if not subject or len(subject) > 80:\n",
    "        return False\n",
    "    return not any(j in subject.lower() for j in\n",
    "                   [\"state form\", \"standard operating\", \"reference number\"])\n",
    "\n",
    "# ---- main ---------------------------------------------------------------\n",
    "\n",
    "def main():\n",
    "    sops = json.loads((SOP_DIR / \"nodes.json\").read_text(encoding=\"utf-8\"))\n",
    "    clean_subj = with_purpose = 0\n",
    "\n",
    "    for s in sops:\n",
    "        p = SOP_DIR / \"text\" / f\"{s['id']}.txt\"\n",
    "        if not p.exists():\n",
    "            s[\"subject\"] = s[\"purpose\"] = None\n",
    "            continue\n",
    "        body = p.read_text(encoding=\"utf-8\")\n",
    "        hdr = parse_header(body)\n",
    "        s[\"reference_number\"] = hdr.get(\"reference_number\")\n",
    "        s[\"subject\"] = hdr.get(\"subject\")\n",
    "        s[\"effective_date\"] = hdr.get(\"effective_date\")\n",
    "        s[\"replaces\"] = hdr.get(\"replaces\")\n",
    "        s[\"purpose\"] = extract_purpose(body)\n",
    "\n",
    "        if looks_clean(s[\"subject\"]):\n",
    "            clean_subj += 1\n",
    "        if s[\"purpose\"]:\n",
    "            with_purpose += 1\n",
    "\n",
    "    out = SOP_DIR / \"nodes_enriched.json\"\n",
    "    out.write_text(json.dumps(sops, indent=2), encoding=\"utf-8\")\n",
    "\n",
    "    print(f\"Parsed {len(sops)} SOPs\")\n",
    "    print(f\"  clean subject:  {clean_subj}\")\n",
    "    print(f\"  has purpose:    {with_purpose}\")\n",
    "    print(f\"  -> {out}\\n\")\n",
    "\n",
    "    # show IIS-001 specifically — the benchmark doc\n",
    "    for s in sops:\n",
    "        if s[\"id\"] == \"2007832\":\n",
    "            print(\"=== IIS-001 (benchmark) ===\")\n",
    "            print(f\"  reference: {s.get('reference_number')}\")\n",
    "            print(f\"  subject:   {s.get('subject')}\")\n",
    "            print(f\"  date:      {s.get('effective_date')}\")\n",
    "            print(f\"  purpose:   {s.get('purpose')}\")\n",
    "            break\n",
    "\n",
    "    print(\"\\n=== sample subjects + purposes ===\")\n",
    "    shown = 0\n",
    "    for s in sops:\n",
    "        if s.get(\"purpose\") and looks_clean(s.get(\"subject\")):\n",
    "            print(f\"\\n  [{s.get('reference_number')}] {s.get('subject')}\")\n",
    "            print(f\"     purpose: {s['purpose'][:140]}...\")\n",
    "            shown += 1\n",
    "            if shown >= 6:\n",
    "                break\n",
    "\n",
    "\n",
    "if __name__ == \"__main__\":\n",
    "    main()"
